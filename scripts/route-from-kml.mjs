// Turns a Google My Maps export (KMZ or KML) with one line per day into a
// route file for the Japan map. Lines must be named by date, e.g. "9.Aug".
//
//   node scripts/route-from-kml.mjs ~/Downloads/lines.kmz 2019 > app/data/routes/hokkaido-hike.ts
//
// Each line is simplified to ~25 m, which is far below what the map can show.
import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { basename } from 'node:path'

const [file, year] = process.argv.slice(2)
if (!file || !/^\d{4}$/.test(year ?? '')) {
  console.error('Usage: node scripts/route-from-kml.mjs <file.kmz|file.kml> <year>')
  process.exit(1)
}

const kml = file.endsWith('.kmz')
  ? execFileSync('unzip', ['-p', file, 'doc.kml'], { encoding: 'utf8', maxBuffer: 64 << 20 })
  : readFileSync(file, 'utf8')

const MONTHS = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec']
const GERMAN = { mär: 'mar', mai: 'may', okt: 'oct', dez: 'dec' }

function parseDate(name) {
  const m = name.trim().match(/^(\d{1,2})\.?\s*([a-zäA-ZÄ]{3})/)
  if (!m) throw new Error(`Line "${name}" is not named like "9.Aug"`)
  const key = m[2].toLowerCase()
  const month = MONTHS.indexOf(GERMAN[key] ?? key) + 1
  if (!month) throw new Error(`Unknown month in "${name}"`)
  return `${year}-${String(month).padStart(2, '0')}-${m[1].padStart(2, '0')}`
}

const R = 6371008.8
const rad = Math.PI / 180

function meters(a, b) {
  const dLat = (b[0] - a[0]) * rad
  const dLng = (b[1] - a[1]) * rad
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a[0] * rad) * Math.cos(b[0] * rad) * Math.sin(dLng / 2) ** 2
  return 2 * R * Math.asin(Math.sqrt(h))
}

// Douglas-Peucker on a local equirectangular plane (fine at hiking scale).
function simplify(points, tolerance) {
  const lat0 = points[0][0] * rad
  const xy = points.map(([lat, lng]) => [lng * rad * Math.cos(lat0) * R, lat * rad * R])
  const keep = new Uint8Array(points.length)
  keep[0] = keep[points.length - 1] = 1
  const stack = [[0, points.length - 1]]
  while (stack.length) {
    const [i, j] = stack.pop()
    const [ax, ay] = xy[i]
    const [bx, by] = xy[j]
    const len = Math.hypot(bx - ax, by - ay) || 1
    let far = -1
    let best = tolerance
    for (let k = i + 1; k < j; k++) {
      const d = Math.abs((bx - ax) * (ay - xy[k][1]) - (ax - xy[k][0]) * (by - ay)) / len
      if (d > best) {
        best = d
        far = k
      }
    }
    if (far > 0) {
      keep[far] = 1
      stack.push([i, far], [far, j])
    }
  }
  return points.filter((_, i) => keep[i])
}

const stages = [...kml.matchAll(/<Placemark>([\s\S]*?)<\/Placemark>/g)]
  .map(([, body]) => {
    const coords = body.match(/<LineString>[\s\S]*?<coordinates>([\s\S]*?)<\/coordinates>/)
    if (!coords) return null
    const name = body.match(/<name>([\s\S]*?)<\/name>/)?.[1] ?? ''
    const points = coords[1].trim().split(/\s+/).map((c) => {
      const [lng, lat] = c.split(',').map(Number)
      return [lat, lng]
    })
    let km = 0
    for (let i = 1; i < points.length; i++) km += meters(points[i - 1], points[i]) / 1000
    return { date: parseDate(name), km: Math.round(km * 10) / 10, path: simplify(points, 25) }
  })
  .filter(Boolean)
  .sort((a, b) => a.date.localeCompare(b.date))

const r4 = n => Math.round(n * 1e4) / 1e4

console.log(`// Generated by scripts/route-from-kml.mjs from ${basename(file)}.
// One stage per walking day; re-run the script instead of editing by hand.
import type { Stage } from '../japan-places'

export const STAGES: Stage[] = [
${stages.map(s => `  {
    date: '${s.date}',
    km: ${s.km},
    path: [${s.path.map(([lat, lng]) => `[${r4(lat)}, ${r4(lng)}]`).join(', ')}]
  }`).join(',\n')}
]`)
console.error(`${stages.length} stages, ${stages.reduce((n, s) => n + s.path.length, 0)} points`)
